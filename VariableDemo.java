class VariableDemo {
	
	public static void main(String[] args){
		
		int a = 4; // Initialization
				
		double b = 5.5; 
		
		char c = 's';
		
		boolean d = true;
	
		System.out.println("Integer : " +a);
		
		System.out.println("Double : " +b);

		System.out.println("Char : " +c);

		System.out.println("Boolean : " +d);
		
		a = 5; //Assignment
		
		System.out.println("Integer : " +a);
		
	}
}