class SwitchDemo {

	public static void main(String[] args){
	
		int ch = 1;
		
		switch(ch){
			case 1 : System.out.println("First Choice");
						break;
			case 2 : System.out.println("Second choice");
						break;
			case 3 : System.out.println("Third choice");
						break;
			default : System.out.println("Wrong choice");			
		}
		
	}
}